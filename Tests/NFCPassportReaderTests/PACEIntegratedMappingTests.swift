    func testAppendixGPaceKey() throws {
        let k = calcSHA1Hash([UInt8]("T22000129364081251010318".utf8))
        XCTAssertEqual(binToHexRep(k), "7E2D2A41C74EA0B38CD36F863939BFA8E9032AAD")
        let gen = SecureMessagingSessionKeyGenerator()
        let key = try gen.deriveKey(keySeed: k, cipherAlgName: "AES", keyLength: 128, nonce: nil, mode: .PACE_MODE, paceKeyReference: 1)
        XCTAssertEqual(binToHexRep(key), "89DED1B26624EC1E634C1989302849DD")
    }

    func testEncryptedNonce() {
        XCTAssertEqual(binToHexRep(AESDecrypt(key: hexRepToBin(kPi), message: hexRepToBin(z), iv: [UInt8](repeating: 0, count: 16))), s)
    }

    func testMapping() throws {
        let m = try PACEIntegratedMapping.map(s: hexRepToBin(s), t: hexRepToBin(t), curveName: NID_brainpoolP256r1, cipherAlg: "AES", keyLength: 128)
        XCTAssertEqual(binToHexRep(m.pseudoRandom), pseudoRandom)
        XCTAssertEqual(binToHexRep(m.rp), rp)
        XCTAssertEqual(binToHexRep(m.generatorX), gx)
        XCTAssertEqual(binToHexRep(m.generatorY), gy)
    }

    /// Uses the EVP_PKEY handed to PACE step 3, so this also checks the mapped generator is set in its group.
    func testKeyAgreementSessionKeysAndTokens() throws {
        let m = try PACEIntegratedMapping.map(s: hexRepToBin(s), t: hexRepToBin(t), curveName: NID_brainpoolP256r1, cipherAlg: "AES", keyLength: 128)
        let params = try m.ephemeralParameters()
        defer { EVP_PKEY_free(params) }
        let group = EC_KEY_get0_group(EVP_PKEY_get0_EC_KEY(params))!
        let ctx = BN_CTX_new()
        defer { BN_CTX_free(ctx) }

        func bn(_ hex: String) -> OpaquePointer { let b = hexRepToBin(hex); return BN_bin2bn(b, Int32(b.count), nil) }
        func encode(_ point: OpaquePointer) -> String {
            var out = [UInt8](repeating: 0, count: 65)
            _ = EC_POINT_point2oct(group, point, POINT_CONVERSION_UNCOMPRESSED, &out, 65, ctx)
            return binToHexRep(out)
        }
        let sk1 = bn(skIc), sk2 = bn(skIfd)
        defer { BN_free(sk1); BN_free(sk2) }
        let p1 = EC_POINT_new(group)!, p2 = EC_POINT_new(group)!, shared = EC_POINT_new(group)!
        defer { EC_POINT_free(p1); EC_POINT_free(p2); EC_POINT_free(shared) }
        XCTAssertEqual(EC_POINT_mul(group, p1, sk1, nil, nil, ctx), 1)
        XCTAssertEqual(EC_POINT_mul(group, p2, sk2, nil, nil, ctx), 1)
        XCTAssertEqual(encode(p1), pkIc)
        XCTAssertEqual(encode(p2), pkIfd)

        XCTAssertEqual(EC_POINT_mul(group, shared, nil, p2, sk1, ctx), 1)
        let x = BN_new()!
        defer { BN_free(x) }
        XCTAssertEqual(EC_POINT_get_affine_coordinates(group, shared, x, nil, ctx), 1)
        var k = [UInt8](repeating: 0, count: 32)
        _ = BN_bn2binpad(x, &k, 32)
        XCTAssertEqual(binToHexRep(k), sharedSecret)

        let gen = SecureMessagingSessionKeyGenerator()
        XCTAssertEqual(binToHexRep(try gen.deriveKey(keySeed: k, cipherAlgName: "AES", keyLength: 128, mode: .ENC_MODE)), ksEnc)
        XCTAssertEqual(binToHexRep(try gen.deriveKey(keySeed: k, cipherAlgName: "AES", keyLength: 128, mode: .MAC_MODE)), ksMac)

        // Authentication tokens: CMAC over 7F49 { 06 OID, 86 public point } (id-PACE-ECDH-IM-AES-CBC-CMAC-128)
        let oid = "060A04007F00070202040402"
        func token(_ point: String) -> String {
            let input = hexRepToBin("7F494F" + oid + "8641" + point)
            return binToHexRep([UInt8](mac(algoName: .AES, key: hexRepToBin(ksMac), msg: input)[0..<8]))
        }
        XCTAssertEqual(token(pkIfd), tIc)
        XCTAssertEqual(token(pkIc), tIfd)
    }

    func testWrongNonceLengthsAreRejected() {
        // AES-192: t must be 24 bytes (k = 192), not 32
        XCTAssertThrowsError(try PACEIntegratedMapping.pseudoRandom(s: [UInt8](repeating: 1, count: 32), t: [UInt8](repeating: 2, count: 32), pBitLength: 256, cipherAlg: "AES", keyLength: 192))
        // 3DES: s must be 16 bytes (l = 128), not one block
        XCTAssertThrowsError(try PACEIntegratedMapping.pseudoRandom(s: [UInt8](repeating: 1, count: 8), t: [UInt8](repeating: 2, count: 16), pBitLength: 256, cipherAlg: "DESede", keyLength: 128))
    }

