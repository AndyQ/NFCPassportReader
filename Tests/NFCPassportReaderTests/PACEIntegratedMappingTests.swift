    func testMatchesSimulatorForEveryCurveAndCipher() throws {
        XCTAssertEqual(vectors.count, 24)
        for v in vectors {
            let (alg, bits): (String, Int) = {
                switch v.cipher {
                    case "TDES": return ("DESede", 128)
                    case "AES_128": return ("AES", 128)
                    case "AES_192": return ("AES", 192)
                    default: return ("AES", 256)
                }
            }()
            let nid = try PACEInfo.getParameterSpec(stdDomainParam: v.parameterId)
            let m = try PACEIntegratedMapping.map(s: hexRepToBin(v.s), t: hexRepToBin(v.t), curveName: nid, cipherAlg: alg, keyLength: bits)
            let label = "parameterId \(v.parameterId) \(v.cipher)"
            XCTAssertEqual(binToHexRep(m.rp), v.rp, label)
            XCTAssertEqual(binToHexRep(m.generatorX), v.gx, label)
            XCTAssertEqual(binToHexRep(m.generatorY), v.gy, label)
        }
    }
